#!/usr/bin/env python3
"""
Generate the StoryGalore native-agent runtime (Cloudflare Agents SDK) from the
agent contracts.

Source of truth:
  - contracts/agents/manifests/*.yaml        (per-agent manifest)
  - contracts/agents/tools/registry.yaml     (tool -> capability mapping)

Output (backend/cloudflare/agents/):
  - src/manifests.ts         simplified manifests for the Policy Engine
  - src/agents/{slug}.ts     one DO agent class per agent
  - src/env.ts               Worker Env type (DO namespaces)
  - src/index.ts             routeAgentRequest entrypoint
  - wrangler.jsonc           DO bindings + SQLite migrations

Regenerate after any change to the agent contracts:
    python3 scripts/generate-agents.py
"""
import json
import os
import re
import subprocess
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parent.parent
MANIFEST_DIR = ROOT / "contracts" / "agents" / "manifests"
TOOLS_REGISTRY = ROOT / "contracts" / "agents" / "tools" / "registry.yaml"
GATEWAY_OPS = ROOT / "contracts" / "agents" / "tools" / "gateway-operations.yaml"
OUT_DIR = ROOT / "backend" / "cloudflare" / "agents"
API_DIR = ROOT / "backend" / "appwrite" / "functions" / "api"

# Worker name. Defaults to the dev instance; override for other environments via
# the AGENTS_WORKER_NAME env var (e.g. storygalore-agents for production).
WORKER_NAME = os.environ.get("AGENTS_WORKER_NAME", "storygalore-agents-dev")

# Tool verbs that produce the agent's own computation (a structured result),
# versus verbs that mutate/read Appwrite or external state via the gateway.
DETERMINISTIC_VERBS = {
    "propose", "review", "assist", "advise", "synthesize",
    "request", "escalate", "delegate", "verify", "validate",
}


def slug_to_const(slug: str) -> str:
    return slug.replace("-", "_").upper()


def camel(words: list[str]) -> str:
    return words[0] + "".join(w.capitalize() for w in words[1:])


def split_tool_name(tool_name: str) -> list[str]:
    return re.split(r"[.\-]", tool_name)


def method_name(tool_name: str) -> str:
    return camel(split_tool_name(tool_name))


def op_name(tool_name: str) -> str:
    """Derive the gateway operation name; `.read` maps to the `_get` convention."""
    segs = split_tool_name(tool_name)
    verb = segs[-1]
    mapped = "get" if verb == "read" else verb
    resource = "_".join(segs[:-1])
    return f"{resource}_{mapped}" if resource else mapped


def load_manifests():
    manifests = {}
    for path in sorted(MANIFEST_DIR.glob("*.yaml")):
        d = yaml.safe_load(open(path))
        manifests[d["slug"]] = d
    return manifests


def load_tool_caps():
    tools = yaml.safe_load(open(TOOLS_REGISTRY))["tools"]
    return {t["id"]: t.get("capability", "") for t in tools}


def load_gateway_ops():
    return yaml.safe_load(open(GATEWAY_OPS)).get("operations", {})


def agent_label(slug: str) -> str:
    """Canonical Appwrite label for an agent. Labels are alphanumeric-only, so the
    slug is encoded by stripping hyphens (e.g. story-producer -> agentstoryproducer)."""
    return "agent" + slug.replace("-", "")


def agent_allowed_ops(manifests, tool_caps, gateway_ops):
    """Map each agent label to the gateway operations its wired tools delegate to."""
    out = {}
    for slug, d in manifests.items():
        ops = set()
        for tool_id in d["tools"]["allowed_tool_ids"]:
            cap = tool_caps.get(tool_id, "")
            op = gateway_ops.get(cap)
            if op:
                ops.add(op)
        if ops:
            out[agent_label(slug)] = sorted(ops)
    return out


def ts_str(value: str) -> str:
    return json.dumps(value, ensure_ascii=False)


def ts_arr(values: list[str]) -> str:
    return "[" + ", ".join(ts_str(v) for v in values) + "]"


def render_manifests(manifests):
    lines = [
        "/**",
        " * Generated by scripts/generate-agents.py from contracts/agents/manifests/*.yaml.",
        " * Do not edit by hand.",
        " */",
        "import type { AgentManifest } from './policy';",
        "",
    ]
    for slug, d in sorted(manifests.items()):
        const = slug_to_const(slug)
        lines.append(f"export const {const}_MANIFEST: AgentManifest = {{")
        lines.append(f"  id: {ts_str(d['id'])},")
        lines.append(f"  slug: {ts_str(d['slug'])},")
        lines.append(f"  name: {ts_str(d['name'])},")
        lines.append(f"  class_name: {ts_str(d['runtime']['class_name'])},")
        lines.append(f"  mode: {ts_str(d['execution']['mode'])},")
        lines.append(f"  mission: {ts_str(d['mission'])},")
        lines.append("  capabilities: {")
        lines.append(f"    allowed: {ts_arr(d['capabilities']['allowed'])},")
        lines.append(f"    forbidden: {ts_arr(d['capabilities']['forbidden'])},")
        lines.append("  },")
        lines.append("  delegation: {")
        lines.append(f"    allowed_agents: {ts_arr(d['delegation']['allowed_agents'])},")
        lines.append("  },")
        lines.append("};")
        lines.append("")
    lines.append("export const MANIFESTS: Record<string, AgentManifest> = {")
    for slug in sorted(manifests):
        const = slug_to_const(slug)
        lines.append(f"  {ts_str(slug.replace('-', '_'))}: {const}_MANIFEST,")
    lines.append("};")
    lines.append("")
    return "\n".join(lines)


def render_agent(slug, d, tool_caps, gateway_ops):
    class_name = d["runtime"]["class_name"]
    const = slug_to_const(slug)
    state_name = f"{class_name}State"
    tool_ids = d["tools"]["allowed_tool_ids"]

    lines = [
        "import { callable } from 'agents';",
        "import { StoryGaloreAgent, type AgentTaskState } from '../base-agent';",
        f"import {{ {const}_MANIFEST }} from '../manifests';",
        "import type { Env } from '../env';",
        "",
        f"interface {state_name} extends AgentTaskState {{}}",
        "",
        f"export class {class_name} extends StoryGaloreAgent<Env, {state_name}> {{",
        f"  protected manifest = {const}_MANIFEST;",
        "",
        f"  initialState: {state_name} = {{",
        "    taskId: '',",
        "    status: 'IDLE',",
        "    provenance: [],",
        "    policyDecisionId: '',",
        "  };",
        "",
    ]
    for tool_id in tool_ids:
        capability = tool_caps.get(tool_id, "")
        tool_name = tool_id[len(slug) + 1:]  # strip "{slug}."
        meth = method_name(tool_name)
        verb = split_tool_name(tool_name)[-1]
        lines.append("  @callable()")
        lines.append(f"  async {meth}(input: unknown): Promise<unknown> {{")
        lines.append(f"    this.assertCapability({ts_str(capability)});")
        if verb in DETERMINISTIC_VERBS:
            lines.append(f"    const {{ provenance, policyDecisionId }} = this.record({ts_str(capability)});")
            lines.append("    return {")
            lines.append(f"      kind: {ts_str(tool_name)},")
            lines.append("      result: input,")
            lines.append("      provenance,")
            lines.append("      policyDecisionId,")
            lines.append("    };")
        else:
            lines.append(f"    this.record({ts_str(capability)});")
            if capability in gateway_ops:
                lines.append(f"    return this.invokeGateway({ts_str(gateway_ops[capability])}, input);")
            else:
                lines.append(f"    // fail-closed: no gateway operation wired for {ts_str(capability)} yet.")
                lines.append(f"    return this.invokeGateway({ts_str(op_name(tool_name))}, input);")
        lines.append("  }")
        lines.append("")
    lines.append("}")
    lines.append("")
    return "\n".join(lines)


def render_agent_test(slug, d):
    const = slug_to_const(slug)
    lines = [
        "import { test } from 'node:test';",
        "import assert from 'node:assert/strict';",
        "import { PolicyEngine, PolicyDeniedError } from '../policy';",
        f"import {{ {const}_MANIFEST }} from '../manifests';",
        "",
        f"test('{slug}: manifest contract is well-formed', () => {{",
        f"  assert.equal({const}_MANIFEST.slug, '{slug}');",
        f"  assert.ok({const}_MANIFEST.capabilities.allowed.length > 0);",
        f"  assert.ok({const}_MANIFEST.capabilities.forbidden.length > 0);",
        "});",
        "",
        f"test('{slug}: allowed capabilities are accepted', () => {{",
        f"  const policy = new PolicyEngine({const}_MANIFEST);",
        f"  for (const cap of {const}_MANIFEST.capabilities.allowed) {{",
        "    assert.doesNotThrow(() => policy.assertCapability(cap), cap);",
        "  }",
        "});",
        "",
        f"test('{slug}: forbidden capabilities are denied', () => {{",
        f"  const policy = new PolicyEngine({const}_MANIFEST);",
        f"  for (const cap of {const}_MANIFEST.capabilities.forbidden) {{",
        "    assert.throws(() => policy.assertCapability(cap), PolicyDeniedError);",
        "  }",
        "});",
        "",
        f"test('{slug}: unknown capability is denied', () => {{",
        f"  const policy = new PolicyEngine({const}_MANIFEST);",
        "  assert.throws(() => policy.assertCapability('__unknown__.capability'), PolicyDeniedError);",
        "});",
        "",
        f"test('{slug}: delegation is enforced', () => {{",
        f"  const policy = new PolicyEngine({const}_MANIFEST);",
        f"  const allowed = {const}_MANIFEST.delegation.allowed_agents;",
        "  if (allowed.includes('*')) {",
        "    assert.doesNotThrow(() => policy.assertDelegation('any-agent'));",
        "  } else {",
        "    for (const target of allowed) {",
        "      assert.doesNotThrow(() => policy.assertDelegation(target), target);",
        "    }",
        "    assert.throws(() => policy.assertDelegation('__unknown__'), PolicyDeniedError);",
        "  }",
        "});",
        "",
    ]
    return "\n".join(lines)


def render_env(manifests):
    lines = [
        "import type { AgentNamespace } from 'agents';",
    ]
    for slug, d in sorted(manifests.items()):
        class_name = d["runtime"]["class_name"]
        lines.append(f"import type {{ {class_name} }} from './agents/{slug}';")
    lines.append("")
    lines.append("/**")
    lines.append(" * Worker environment. Each durable-object binding is required by")
    lines.append(" * `routeAgentRequest`; the Appwrite gateway credentials are optional (agents")
    lines.append(" * fail closed when they are not configured, so local dev works without")
    lines.append(" * production secrets).")
    lines.append(" */")
    lines.append("export type Env = {")
    for slug, d in sorted(manifests.items()):
        class_name = d["runtime"]["class_name"]
        lines.append(f"  {class_name}: AgentNamespace<{class_name}>;")
    lines.append("  APPWRITE_ENDPOINT?: string;")
    lines.append("  APPWRITE_PROJECT_ID?: string;")
    lines.append("  APPWRITE_API_KEY?: string;")
    lines.append("  AGENT_SESSION_JWT?: string;")
    lines.append("};")
    lines.append("")
    return "\n".join(lines)


def render_index(manifests):
    lines = [
        "import { routeAgentRequest } from 'agents';",
    ]
    for slug, d in sorted(manifests.items()):
        class_name = d["runtime"]["class_name"]
        lines.append(f"import {{ {class_name} }} from './agents/{slug}';")
    lines.append("import type { Env } from './env';")
    lines.append("")
    exports = ", ".join(d["runtime"]["class_name"] for _, d in sorted(manifests.items()))
    lines.append(f"export {{ {exports} }};")
    lines.append("")
    lines.append("export default {")
    lines.append("  async fetch(request: Request, env: Env): Promise<Response> {")
    lines.append("    return (")
    lines.append("      (await routeAgentRequest(request, env)) ?? new Response('Not found', { status: 404 })")
    lines.append("    );")
    lines.append("  },")
    lines.append("} satisfies ExportedHandler<Env>;")
    lines.append("")
    return "\n".join(lines)


def render_agent_auth(manifests, tool_caps, gateway_ops):
    allowed = agent_allowed_ops(manifests, tool_caps, gateway_ops)
    lines = [
        "package handler",
        "",
        "// Code generated by scripts/generate-agents.py. DO NOT EDIT.",
        "",
        "// agentAllowedOperations maps an agent label to the set of gateway operations",
        "// its wired tools delegate to (contracts/agents/tools/gateway-operations.yaml).",
        "// Agent actors (Appwrite users carrying one of these alphanumeric labels, e.g.",
        "// `agentstoryproducer`) may only call these operations; the dispatch enforces",
        "// this before any handler runs.",
        "var agentAllowedOperations = map[string]map[string]bool{",
    ]
    for label, ops in sorted(allowed.items()):
        entries = ", ".join(f'"{op}": true' for op in ops)
        lines.append(f'\t"{label}": {{{entries}}},')
    lines.append("}")
    lines.append("")
    return "\n".join(lines)


def render_wrangler(manifests):
    classes = sorted(d["runtime"]["class_name"] for d in manifests.values())
    # v1 preserves the two classes deployed in the vertical slice; new classes
    # go in v2 so the migration history is never edited.
    v1 = ["StoryProducerAgent", "SupportAgent"]
    v2 = [c for c in classes if c not in v1]
    bindings = [{"name": c, "class_name": c} for c in classes]
    migrations = [{"tag": "v1", "new_sqlite_classes": v1}]
    if v2:
        migrations.append({"tag": "v2", "new_sqlite_classes": v2})
    doc = {
        "name": WORKER_NAME,
        "main": "src/index.ts",
        "compatibility_date": "2026-10-21",
        "compatibility_flags": ["nodejs_compat"],
        "observability": {"enabled": True},
        "durable_objects": {"bindings": bindings},
        "migrations": migrations,
    }
    return json.dumps(doc, indent=2) + "\n"


def main():
    manifests = load_manifests()
    tool_caps = load_tool_caps()
    gateway_ops = load_gateway_ops()

    (OUT_DIR / "src").mkdir(parents=True, exist_ok=True)
    (OUT_DIR / "src" / "agents").mkdir(parents=True, exist_ok=True)

    (OUT_DIR / "src" / "manifests.ts").write_text(render_manifests(manifests))
    (OUT_DIR / "src" / "env.ts").write_text(render_env(manifests))
    (OUT_DIR / "src" / "index.ts").write_text(render_index(manifests))
    (OUT_DIR / "wrangler.jsonc").write_text(render_wrangler(manifests))

    for slug, d in manifests.items():
        (OUT_DIR / "src" / "agents" / f"{slug}.ts").write_text(
            render_agent(slug, d, tool_caps, gateway_ops)
        )
        (OUT_DIR / "src" / "agents" / f"{slug}.test.ts").write_text(render_agent_test(slug, d))

    # Go agent allowlist consumed by the `api` gateway function.
    (API_DIR / "agent_auth.go").write_text(render_agent_auth(manifests, tool_caps, gateway_ops))

    print(f"generated {len(manifests)} agents ({len(gateway_ops)} gateway ops wired) -> {OUT_DIR}")


if __name__ == "__main__":
    main()
